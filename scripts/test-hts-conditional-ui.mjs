import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const js=readFileSync('js/hts-shipment.js','utf8');
const start=js.indexOf('function relevantMeasures(');
const end=js.indexOf('function renderLine(');
assert(start>=0&&end>start,'Renderer helpers must exist');
const esc=s=>String(s??'').replaceAll('&','&amp;').replaceAll('<','&lt;');
const money=n=>n==null?'Review':'$'+Number(n).toFixed(2);
const {comparisonTable,renderAgencyReview}=new Function('esc','money',js.slice(start,end)+';return {comparisonTable,renderAgencyReview};')(esc,money);
const screening=(measures=[])=>({sourceVerified:true,measures,unpriced:[],totalDuty:1000});
const tariff=(program,hts)=>({program,hts,ratePercent:25,rateMode:'additional'});
const mk=(country,screenings)=>({input:{country,lineIndex:0,customsValue:1000},comparison:screenings.map((x,i)=>({hts:'123456789'+i,displayHts:'1234.56.789'+i,description:'Product',ordinaryRate:'Free',screening:x}))});
let html=comparisonTable(mk('CN',[screening([tariff('Section 301','9903.88.03')]),screening([])]));
assert(html.includes('<th>Section 301</th>'));
assert(!html.includes('Section 338')&&!html.includes('Section 232'));
assert(!html.includes('No additional rate identified'));
assert.equal((html.match(/<th>Section 301<\/th>/g)||[]).length,1);
html=comparisonTable(mk('CA',[screening([tariff('Section 338','9903.03.14')]),screening([])]));
assert(html.includes('<th>Section 338</th>'));
assert(!html.includes('Section 301')&&!html.includes('Section 232'));
html=comparisonTable(mk('CN',[screening([tariff('Section 338','9903.03.14')])]));
assert(!html.includes('Section 338'),'Never show Canadian tariff for non-Canada origin');
html=comparisonTable(mk('KR',[screening([])]));
assert(!html.includes('<th>Section '),'No irrelevant tariff columns');
const pga={note:'Agency flags not verified',rows:[{agency:'FDA',requirement:'Prior Notice',status:'Possible',url:'https://www.fda.gov/'},{agency:'FMC',requirement:'Ocean rules'}]};
const baseline={input:{country:'CN'},pga,screening:screening([]),rules:{section338:{inNote51List:true,hts:'9903.03.14'}}};
html=renderAgencyReview(baseline);
assert(html.includes('FDA'));
assert(!html.includes('FMC'));
assert(!html.includes('Section 338'));
html=renderAgencyReview({...baseline,pga:{rows:[]},input:{country:'KR'},rules:{}});
assert(!html.includes('Potential government agency requirements'));
const canada=renderAgencyReview({...baseline,input:{country:'CA'},rules:{section338:{inNote51List:true,hts:'9903.03.14',message:'Applies',sourceRevision:23,status:'applicable',reference:'https://hts.usitc.gov/'}}});
assert(canada.includes('Section 338'));
const exempt=renderAgencyReview({...baseline,input:{country:'CA'},rules:{section338:{inNote51List:false}}});
assert(!exempt.includes('Section 338'));
console.log('PASS conditional Chapter 99 table, Canada-only 338, and PGA visibility');
