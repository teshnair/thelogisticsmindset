import assert from 'node:assert/strict';
import fs from 'node:fs';
import { supplementalScreening } from '../lib/trade-screening.mts';
const index=JSON.parse(fs.readFileSync('data/chapter99-index.json','utf8'));
assert.ok(index.htsRevision>=20,'Chapter 99 legal index must be revision 20 or newer');
assert.match(index.headings['9903.03.14'].legalContext['51:b'], /7308\.90\.30/);
assert.match(index.headings['9903.03.14'].legalContext['51:b'], /9507\.10\.0040/);
assert.equal(index.stats.validatedCandidateLinks,Object.values(index.codes).reduce((n,a)=>n+a.length,0));
const screen=(hts,country='CA',facts={})=>supplementalScreening(hts,country,facts,index,new Date('2026-09-29T16:00:00Z'));
assert.equal(screen('8711500000').notices[0].status,'may-apply');
assert.equal(screen('8711500000','CA',{importedBeforeBan:'no'}).notices[0].status,'prohibited');
assert.equal(screen('8711500000','CA',{importedBeforeBan:'yes'}).notices.length,0);
assert.equal(screen('8711500000','US').notices.length,0);
assert.equal(screen('8703230100').notices.length,0);
assert.equal(screen('7320103000').notices.length,0);
assert.equal(screen('0404100500','CA',{importedBeforeBan:'no'}).notices[0].status,'prohibited');
assert.equal(screen('2203000060','CA',{packagedAlcohol:'no'}).notices.length,0);
assert.equal(screen('2203000060','CA',{packagedAlcohol:'yes',importedBeforeBan:'no'}).notices[0].status,'prohibited');
assert.equal(screen('22083060','CA',{importedBeforeBan:'no'}).notices[0].status,'may-apply');
assert.equal(screen('8711500000','CA',{entryDate:'2026-09-28'}).notices.length,0);
assert.equal(screen('3004909200').blocksTotal,true);
assert.equal(screen('8541430010','CN').notices[0].kind,'polysilicon');
assert.equal(screen('8541430010','CN',{entryDate:'2026-12-04'}).notices.length,0);
assert.equal(screen('1701141000','BR').notices[0].kind,'quota');
console.log('Regulatory release tests passed: Revision 20 integrity; Canadian prohibition scope, packaging and dates; pharmaceutical review; polysilicon dates; sugar quota.');
