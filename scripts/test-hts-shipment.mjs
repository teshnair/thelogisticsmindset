const input={hts:'7308903000',country:'CA',customsValue:1000,quantity1:10,unit1:'kg'};
const base={rates:{appliedRate:'5%'}};
const rules={revisionVerified:true,status:'resolved',measures:[{program:'Section 232',hts:'9903.82.02',rateMode:'additional',applicability:'applicable',estimatedDuty:500,ratePercent:50,noteTargets:['16:c']},{program:'Section 338',hts:'9903.03.14',rateMode:'additional',applicability:'applicable',estimatedDuty:500,ratePercent:50}]};
let e=lineEstimate(input,base,rules);
assert.equal(e.measures[0].amount,null,'Missing metal origin must not be assumed');
assert.equal(e.knownTariffs,500);
assert.equal(e.complete,false);
e=lineEstimate({...input,meltPourCountry:'CA'},base,rules);
assert.equal(e.complete,true);assert.equal(e.knownTariffs,1000);
assert.equal(lineEstimate({...input,quantity1:'',unit1:''},base,rules).ordinary.amount,50,'Value-based duty calculates without optional quantities');
assert.equal(lineEstimate(input,base,{...rules,revisionVerified:false}).knownTariffs,0);
assert.equal(lineEstimate(input,base,{...rules,totalRequiresReview:true}).complete,false);
const replacement={...rules,measures:[{applicability:'applicable',rateMode:'replacement',replacementDutyEstimate:200,ratePercent:20}]};
assert.equal(lineEstimate(input,base,replacement).complete,false);assert.equal(lineEstimate(input,base,replacement).knownTariffs,0);
const foodInput={hts:'2008991500',country:'CO',customsValue:36000,quantity1:'',unit1:'',quantity2:'',unit2:''};
const cleanRules={revisionVerified:true,status:'resolved',measures:[]};
const foodEstimate=lineEstimate(foodInput,{rates:{appliedRate:'0.8%'}},cleanRules);
assert.equal(foodEstimate.ordinary.amount,288,'2008.99.15.00 MFN 0.8% of $36,000 calculates without quantity');
let foodSummary=summarizeShipment([{input:foodInput,estimate:foodEstimate}],'ocean','2026-10-28');
assert.equal(foodSummary.baseDuty,288);
assert.equal(foodSummary.tariffs,0);
assert.equal(foodSummary.mpf,124.70);
assert.equal(foodSummary.hmf,45);
assert.equal(foodSummary.total,457.70,'Illustrative total when no additional measures exist');
const unresolvedEstimate=lineEstimate(foodInput,{rates:{appliedRate:'0.8%'}},{...cleanRules,revisionVerified:false});
foodSummary=summarizeShipment([{input:foodInput,estimate:unresolvedEstimate}],'ocean','2026-10-28');
assert.equal(foodSummary.baseDuty,288,'Known ordinary duty must still show');
assert.equal(foodSummary.tariffs,null,'Unknown additional duties are not zero');
assert.equal(foodSummary.identifiedSubtotal,457.70,'Known amounts subtotal retains duty and fees');
assert.equal(foodSummary.total,null,'Unknown tariffs prevent declaring a full total');
assert.equal(lineEstimate(foodInput,{rates:{appliedRate:'10¢/kg'}},cleanRules).ordinary.amount,null,'Specific rate needs quantity');
assert.equal(lineEstimate(foodInput,{rates:{appliedRate:'0.8% + 10¢/kg'}},cleanRules).ordinary.amount,null,'Compound rate needs quantity');
assert.equal(lineEstimate({...foodInput,hts:'20089915'},{rates:{appliedRate:'0.8%'}},cleanRules).ordinary.amount,null,'Broad HTS does not produce shipment dollar amount');
